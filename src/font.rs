/// 渲染一行文字到 framebuffer
/// `x`, `y` 是起始位置（左上角）
/// `scale` 是像素放大倍数（例如 2 表示每个字体像素画为 2x2）
/// `color` 是 (r, g, b) 各 0.0-1.0
pub fn draw_text<F: Frame>(
    f: &mut F,
    text: &str,
    start_x: i32,
    start_y: i32,
    scale: i32,
    color: (f32, f32, f32),
    alpha: f32,
) {
    let mut cx = start_x;
    for ch in text.chars() {
        if let Some(cols) = char_bitmap(ch) {
            for (col_idx, &col_bits) in cols.iter().enumerate() {
                for row in 0..7 {
                    if col_bits & (1 << row) != 0 {
                        let px = cx + col_idx as i32 * scale;
                        let py = start_y + row as i32 * scale;
                        let rect = Rectangle::<i32, Physical>::new(
                            Point::new(px, py), Size::new(scale, scale));
                        f.clear(Color32F::new(color.0, color.1, color.2, alpha), &[rect]).ok();
                    }
                }
            }
            cx += (5 + 1) * scale; // 5px char + 1px spacing
        } else {
            cx += 3 * scale; // unknown char: small gap
        }
    }
}

/// 计算文字渲染后的宽度
pub fn text_width(text: &str, scale: i32) -> i32 {
    let chars = text.chars().filter(|c| char_bitmap(*c).is_some()).count();
    (chars as i32 * (5 + 1) - 1) * scale
}

